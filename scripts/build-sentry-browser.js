// Builds shared/sentry.min.js from scripts/sentry-browser-entry.js.
// Run with `pnpm run build:sentry`. The output is committed, so Render needs no
// build step.
//
// Note: the trackers' service workers cache files cache-first, so players who
// already have the old file only get a rebuilt one after a tracker's
// CACHE_NAME is bumped.
const path = require('path');
const esbuild = require('esbuild');
const { version } = require('@sentry/browser/package.json');

const root = path.join(__dirname, '..');

esbuild
  .build({
    entryPoints: [path.join(root, 'scripts', 'sentry-browser-entry.js')],
    outfile: path.join(root, 'shared', 'sentry.min.js'),
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2020',
    legalComments: 'none',
    banner: {
      js: `/* Sentry browser SDK ${version} (MIT license). Generated by scripts/build-sentry-browser.js: do not edit. */`,
    },
  })
  .then(() => console.log(`Built shared/sentry.min.js with @sentry/browser ${version}`))
  .catch(() => process.exit(1));
